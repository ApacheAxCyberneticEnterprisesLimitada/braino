import { createHash } from "node:crypto";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const baselineSql = readFileSync(join(root, "src/schema.sql"), "utf8");
const files = readdirSync(join(root, "migrations"))
  .filter((name) => /^\d{3}_[a-z0-9_]+\.sql$/.test(name))
  .sort();

const expected = files.map((_, index) => String(index + 1).padStart(3, "0"));
const actual = files.map((name) => name.slice(0, 3));
if (actual.some((version, index) => version !== expected[index])) {
  throw new Error(`Migration versions must be contiguous from 001; found ${actual.join(", ")}.`);
}

const checksum = (sql) => createHash("sha256").update(sql).digest("hex");
const migrations = files.map((file) => {
  const sql = readFileSync(join(root, "migrations", file), "utf8");
  return {
    version: Number(file.slice(0, 3)),
    name: file.slice(0, -4),
    checksum: checksum(sql),
    sql,
  };
});

const banner = "// AUTO-GENERATED by scripts/embed-migrations.mjs — do not edit by hand.\n";
const out = `${banner}
export interface EmbeddedMigration {
  version: number;
  name: string;
  checksum: string;
  sql: string;
}

export const BASELINE_SQL: string = ${JSON.stringify(baselineSql)};

export const MIGRATIONS: readonly EmbeddedMigration[] = ${JSON.stringify(migrations, null, 2)};
`;

writeFileSync(join(root, "src/schema-embedded.ts"), out);
console.log(`embed-migrations: wrote the baseline and ${migrations.length} migrations`);
